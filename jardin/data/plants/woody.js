// Catalogue des essences ligneuses (arbres, arbustes, haies, fruitiers, grimpantes).
// Schéma : voir jardin/SPECS.md §16. Chaque entrée est un objet Plant ordinaire ;
// le helper `mk` ne fait que réduire la répétition (soleil abrégé, entretien par défaut).
const SUN = { F: "full", P: "partial", S: "shade" };
const WATER = { l: "low", m: "medium", h: "high" };
const FOL = { d: "deciduous", e: "evergreen", s: "semi" };
const MAINT = { l: "low", m: "medium", h: "high" };

function mk(id, commonName, latinName, category, heightAdult, widthAdult, sun, hardiness,
  water, soil, foliage, bloom, bloomColor, zones, maintenance, kc, spacing, extra, c) {
  return {
    id, commonName, latinName, category, heightAdult, widthAdult,
    sun: sun.split("").map(s => SUN[s]),
    hardiness, water: WATER[water], soil, foliage: FOL[foliage],
    bloom, bloomColor, zones,
    ...extra,
    maintenance: MAINT[maintenance], kc, spacing,
    care: {
      plantMonths: c[0], pruneMonths: c[1], fertMonths: c[2],
      planting: c[3], pruning: c[4], fertilizer: c[5], watering: c[6], notes: c[7],
    },
  };
}

