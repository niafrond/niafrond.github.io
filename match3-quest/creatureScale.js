/** Largeur à donner au sprite d'un ennemi, en cases. `boss` : boss ou mirage de boss. */
export function creatureSize(templateId, boss = false) {
    const s = ENEMY_SCALE[templateId];
    if (!s) return boss ? LEGACY_BOSS_SIZE : LEGACY_SIZE;
    return +Math.min(boss ? MAX_BOSS_SIZE : MAX_SIZE, s[0] * (boss ? s[1] : 1) / FILL).toFixed(3);
}
